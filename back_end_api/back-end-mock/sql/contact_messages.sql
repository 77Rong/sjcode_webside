-- ============================================================
-- 联系我们留言表（contact_messages）
--
-- 用途：前台「联系我们」表单提交的留言，后台「联系管理」页面读取 / 处理 / 删除。
--   - 后端 back-end-mock 通过 service_role 读写（service_role 具备 BYPASSRLS）
--   - 前台不直连数据库，统一经后端 /api/contact 转发
--
-- 执行方式：Supabase Dashboard -> SQL Editor -> 新建查询 -> 粘贴本脚本 -> Run
-- ============================================================

-- ---------- 建表 ----------
create table if not exists public.contact_messages (
  id         bigint generated by default as identity primary key,
  name       text        not null,
  email      text        not null,
  phone      text        not null default '',
  message    text        not null,
  -- 处理状态：pending 未处理 / processed 已处理
  status     text        not null default 'pending',
  -- 处理备注
  reply      text        not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- ---------- 索引 ----------
-- 列表默认按提交时间倒序
create index if not exists contact_messages_created_at_idx
  on public.contact_messages (created_at desc);

-- 状态筛选
create index if not exists contact_messages_status_idx
  on public.contact_messages (status);

-- ---------- updated_at 自动刷新 ----------
create or replace function public.set_contact_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists contact_messages_set_updated_at on public.contact_messages;
create trigger contact_messages_set_updated_at
before update on public.contact_messages
for each row execute function public.set_contact_updated_at();

-- ---------- 行级安全 ----------
-- 开启 RLS 后，仅 service_role（后端）可访问；前端不直连数据库，无 anon 策略。
alter table public.contact_messages enable row level security;

